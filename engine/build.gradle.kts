import io.gitlab.arturbosch.detekt.extensions.DetektExtension
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.serialization)
}

// Parameter tables (docs/04 §6) are JSON files under engine/params/, reviewed by the childcare reviewer.
// They are embedded into commonMain as Kotlin string constants so every KMP target can read them
// without platform resource loading.
val paramsDir = layout.projectDirectory.dir("params")
val generatedParamsDir = layout.buildDirectory.dir("generated/params/commonMain/kotlin")

val generateBundledParams by tasks.registering {
    description = "Embeds engine/params/**/*.json into BundledParamFiles.kt."
    inputs.dir(paramsDir)
    outputs.dir(generatedParamsDir)
    doLast {
        val root = paramsDir.asFile
        val entries =
            root
                .walkTopDown()
                .filter { it.isFile && it.extension == "json" }
                .sortedBy { it.relativeTo(root).invariantSeparatorsPath }
                .joinToString(separator = "\n") { file ->
                    val key = file.relativeTo(root).invariantSeparatorsPath
                    val body = file.readText().replace("$", "\${'$'}")
                    require(!body.contains("\"\"\"")) { "$key must not contain triple quotes" }
                    "        \"$key\" to \"\"\"$body\"\"\","
                }
        val out = generatedParamsDir.get().file("dev/babysim/engine/params/BundledParamFiles.kt").asFile
        out.parentFile.mkdirs()
        out.writeText(
            """
            |// GENERATED by :engine:generateBundledParams from engine/params. Do not edit.
            |package dev.babysim.engine.params
            |
            |internal object BundledParamFiles {
            |    val files: Map<String, String> =
            |        mapOf(
            |$entries
            |        )
            |}
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    // v1: JVM only (consumed by :harness now, :app later). iOS targets are added at Step 11.
    jvm {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    compilerOptions {
        allWarningsAsErrors.set(true)
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generateBundledParams)
            dependencies {
                implementation(libs.kotlinx.serialization.json)
            }
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
    }
}

extensions.configure<DetektExtension> {
    config.setFrom(rootProject.file("config/detekt/detekt.yml"), rootProject.file("config/detekt/engine.yml"))
    source.setFrom(
        "src/commonMain/kotlin",
        "src/commonTest/kotlin",
        "src/jvmMain/kotlin",
        "src/jvmTest/kotlin",
    )
}

tasks.named<Test>("jvmTest") {
    systemProperty(
        "engine.sourceRoot",
        layout.projectDirectory
            .dir("src")
            .asFile.absolutePath,
    )
}

// KMP has no `test` task; alias it so `./gradlew test` (CLAUDE.md) also runs engine tests.
tasks.register("test") {
    group = "verification"
    description = "Runs all engine tests (alias for jvmTest)."
    dependsOn("jvmTest")
}
